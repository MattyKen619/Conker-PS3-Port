# Writes the SPU build's copies of librecomp/rsp_vu.hpp and librecomp/rsp_vu_impl.hpp from the runtime's,
# with changes for speed on the SPU (results identical; checked with tools/spu-sim on recorded tasks):
#  - VMACF, VMULF: the 64-bit multiply done as a 32-bit one (16 x 16 bits always fits) and widened.
#    The SPU has no 64-bit multiply: these were calls to __muldi3, 23% of the SPU's time.
#  - Vector registers 16-byte aligned, and LQV/SQV/LDV/SDV with element 0 done on whole quadwords
#    (rotate and select) instead of byte by byte, when they stay within one 16-byte line of DMEM.
#   gen_vu_impl.py rsp_vu.hpp rsp_vu_impl.hpp out_dir
import sys, os
vu, impl, out = sys.argv[1], sys.argv[2], sys.argv[3]

def edit(src, old, new, name):
    if src.count(old) != 1:
        sys.exit("gen_vu_impl.py (%s): expected exactly one of: %s" % (name, old))
    return src.replace(old, new)

s = open(vu).read()
s = edit(s, "    union r128 {", "    union alignas(16) r128 {", "rsp_vu.hpp")
s = edit(s, "#include <cstdint>\n", "#include <cstdint>\n#include <spu_intrinsics.h>\n", "rsp_vu.hpp")
open(os.path.join(out, "rsp_vu.hpp"), "w").write("// Generated by ps3/spu/audio/gen_vu_impl.py from librecomp/rsp_vu.hpp.\n" + s)

s = open(impl).read()
s = edit(s, "accumulatorSet(n, accumulatorGet(n) + (s64)vs.s16(n) * (s64)vte.s16(n) * 2);",
            "accumulatorSet(n, accumulatorGet(n) + (s64)(s32)(vs.s16(n) * vte.s16(n)) * 2);", "VMACF")
s = edit(s, "accumulatorSet(n, (s64)vs.s16(n) * (s64)vte.s16(n) * 2 + 0x8000);",
            "accumulatorSet(n, (s64)(s32)(vs.s16(n) * vte.s16(n)) * 2 + 0x8000);", "VMULF")
helpers = '''
// SPU quadword versions of the common vector loads and stores (DMEM is 16-byte aligned, big-endian,
// laid out as on the N64; vector registers too).
static inline vec_uchar16& spu_q(RSP::r128& r) { return *reinterpret_cast<vec_uchar16*>(&r); }
static inline vec_uchar16& spu_dmem_line(u32 a) { return *reinterpret_cast<vec_uchar16*>(dmem + (a & 0xFF0)); }
static const vec_uchar16 spu_ones = {255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 255};
static const vec_uchar16 spu_first8 = {255, 255, 255, 255, 255, 255, 255, 255, 0, 0, 0, 0, 0, 0, 0, 0};
'''
s = edit(s, "template<u8 e>\nauto RSP::LBV(", helpers + '#include "rsp_vu_spu.hpp"\n' + "\ntemplate<u8 e>\nauto RSP::LBV(", "helpers")
# The SIMD versions (ps3/spu/include/rsp_vu_spu.hpp) of the hottest arithmetic instructions.
for op in ["VADD", "VSUB", "VMADH", "VMADN", "VMADM", "VMADL", "VMUDH", "VMUDM", "VMUDN", "VMUDL"]:
    head = "auto RSP::%s(r128& vd, cr128& vs, cr128& vt) -> void {\n" % op
    s = edit(s, head, head + "    spuvu::%s<e>(*this, vd, vs, vt);\n    return;\n" % op, op)
for op in ["VMULF", "VMACF"]:  # the signed forms (U = 0); VMULU/VMACU keep the scalar code
    head = "auto RSP::%s(r128& vd, cr128& vs, cr128& vt) -> void {\n" % op
    s = edit(s, head, head + "    if constexpr (!U) { spuvu::%s<e>(*this, vd, vs, vt); return; }\n" % op, op)
s = edit(s, '''auto RSP::LQV(r128& vt, cr32& rs, s8 imm) -> void {
    auto address = rs + imm * 16;
''', '''auto RSP::LQV(r128& vt, cr32& rs, s8 imm) -> void {
    auto address = rs + imm * 16;
    if constexpr (e == 0) {  // bytes 0 .. 15 - (address & 15) from DMEM up to the end of its line
        const u32 off = address & 15;
        spu_q(vt) = spu_sel(spu_q(vt), spu_rlqwbyte(spu_dmem_line(address), off), spu_slqwbyte(spu_ones, off));
        return;
    }
''', "LQV")
s = edit(s, '''auto RSP::LDV(r128& vt, cr32& rs, s8 imm) -> void {
    auto address = rs + imm * 8;
''', '''auto RSP::LDV(r128& vt, cr32& rs, s8 imm) -> void {
    auto address = rs + imm * 8;
    if constexpr (e == 0) {
        const u32 off = address & 15;
        if (off <= 8) {  // bytes 0-7 from DMEM, within one line
            spu_q(vt) = spu_sel(spu_q(vt), spu_rlqwbyte(spu_dmem_line(address), off), spu_first8);
            return;
        }
    }
''', "LDV")
s = edit(s, '''auto RSP::SDV(cr128& vt, cr32& rs, s8 imm) -> void {
    auto address = rs + imm * 8;
''', '''auto RSP::SDV(cr128& vt, cr32& rs, s8 imm) -> void {
    auto address = rs + imm * 8;
    if constexpr (e == 0) {
        const u32 off = address & 15;
        if (off <= 8) {  // bytes 0-7 to DMEM, within one line
            vec_uchar16& line = spu_dmem_line(address);
            const vec_uchar16 v = *reinterpret_cast<const vec_uchar16*>(&vt);
            line = spu_sel(line, spu_rlmaskqwbyte(v, -(int)off), spu_rlmaskqwbyte(spu_first8, -(int)off));
            return;
        }
    }
''', "SDV")
s = edit(s, '''auto RSP::SQV(cr128& vt, cr32& rs, s8 imm) -> void {
    auto address = rs + imm * 16;
''', '''auto RSP::SQV(cr128& vt, cr32& rs, s8 imm) -> void {
    auto address = rs + imm * 16;
    if constexpr (e == 0) {  // bytes 0 .. 15 - (address & 15) to DMEM up to the end of its line
        const u32 off = address & 15;
        vec_uchar16& line = spu_dmem_line(address);
        const vec_uchar16 v = *reinterpret_cast<const vec_uchar16*>(&vt);
        line = spu_sel(line, spu_rlmaskqwbyte(v, -(int)off), spu_rlmaskqwbyte(spu_ones, -(int)off));
        return;
    }
''', "SQV")
open(os.path.join(out, "rsp_vu_impl.hpp"), "w").write("// Generated by ps3/spu/audio/gen_vu_impl.py from librecomp/rsp_vu_impl.hpp.\n" + s)
