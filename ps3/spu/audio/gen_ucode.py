src = open(sys.argv[1]).read()
start = src.index('RspExitReason conker_audio_ucode_initial(uint8_t* rdram, RspContext* ctx) {')
head = '''// Generated by ps3/spu/audio/gen_ucode.py from RecompiledFuncs/rsp/audio_ucode.cpp.
#include "librecomp/rsp.hpp"
#include "librecomp/rsp_vu_impl.hpp"
#define printf(...) ((void)0)
RspExitReason conker_audio_ucode_initial(uint8_t* rdram, RspContext* ctx);
RspExitReason conker_audio_ucode0(uint8_t* rdram, RspContext* ctx);
RspExitReason conker_audio_ucode1(uint8_t* rdram, RspContext* ctx);
'''
open(sys.argv[2], 'w').write(head + src[start:])
