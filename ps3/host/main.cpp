    void request_quit() {
        if (!quit_requested.exchange(true)) {
            ultramodern::quit();
        }
    }
    std::string failure_message;
    std::chrono::steady_clock::time_point start_time;
    [[noreturn]] void finish_test(bool show_dialog);

    // --- Same game setup as CBFD-Recompiled's host -----------------------------------------

    void set_fr_mode(recomp_context* ctx) {
        constexpr uint32_t STATUS_FR = 0x04000000;
        cop0_status_write(ctx, ctx->status_reg | STATUS_FR);
    }

    void on_thread_create(uint8_t*, recomp_context* ctx) {
        set_fr_mode(ctx);
    }

    void on_init(uint8_t* rdram, recomp_context* ctx) {
        std::printf("[ps3] on_init: game memory at %p\n", (void*)rdram);
        set_fr_mode(ctx);
        conker::register_tlb_mapped_code();
        conker::map_tlb_code_pages(rdram);
        constexpr int32_t osCicId = 0x80000310;
        MEM_W(osCicId, 0) = 6105;
        constexpr int32_t osRunningThread = 0x8002BE00;
        ultramodern::set_running_thread_variable(osRunningThread);
        std::printf("[ps3] on_init done, starting game code\n");
    }

    // The audio microcode runs on an SPU (ps3/spu/audio, ~7x faster than the PPU and off it), or on the
    // PPU if the SPU program couldn't start or stops answering.
    SpuAudio spu_audio;
    RspExitReason counted_audio_ucode(uint8_t* rdram, uint32_t ucode_addr) {
        ++audio_tasks;
        uint64_t t0 = ps3prof_now();
        RspExitReason r;
        if (spu_audio.running()) {
            r = spu_audio.run(rdram, ucode_addr);
            if (spu_audio.running()) {
                ps3prof_audio_spu(spu_audio.last_ticks());
                ps3prof_audio_task(ps3prof_now() - t0);
                return r;
            }
            std::printf("[ps3] audio microcode back on the PPU\n");
        }
        r = conker_audio_ucode(rdram, ucode_addr);
        ps3prof_audio_task(ps3prof_now() - t0);
        return r;
    }

    RspUcodeFunc* get_rsp_microcode(const OSTask* task) {
        if (task->t.type == M_AUDTASK) {
            return counted_audio_ucode;
        }
        std::printf("[ps3] no RSP microcode for task type %u\n", (unsigned)task->t.type);
        return nullptr;
    }

