# Writes rsp_tables.h: the RSP's reciprocal and inverse square root tables (as librecomp's rsp.cpp
# computes them at startup, from the Ares emulator). Computing them on the SPU took ~5 billion
# instructions (64-bit multiplies in software): seconds at startup.
import sys
rec = [0xFFFF] + [((1 << 34) // (i + 512) + 1) >> 8 & 0xFFFF for i in range(1, 512)]
rsq = []
for i in range(512):
    a = (i + 512) >> (1 if i % 2 == 1 else 0)
    # largest b with a * (b + 1)^2 < 2^44, searching up from 2^17 as the original does
    b = 1 << 17
    lo, hi = b, 1 << 23
    while a * (hi + 1) * (hi + 1) < (1 << 44): hi *= 2
    # binary search for the first b >= 2^17 where a*(b+1)^2 >= 2^44
    if a * (b + 1) * (b + 1) < (1 << 44):
        while lo < hi:
            mid = (lo + hi) // 2
            if a * (mid + 1) * (mid + 1) < (1 << 44): lo = mid + 1
            else: hi = mid
        b = lo
    rsq.append((b >> 1) & 0xFFFF)
def arr(name, v):
    return "const uint16_t %s[512] = {\n%s\n};\n" % (name, ",\n".join(", ".join("0x%04X" % x for x in v[i:i + 16]) for i in range(0, 512, 16)))
open(sys.argv[1], "w").write("// Generated by gen_tables.py.\n#include <stdint.h>\n" + arr("kRspReciprocals", rec) + arr("kRspInverseSquareRoots", rsq))
