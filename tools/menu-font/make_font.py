#!/usr/bin/env python3
# Renders the startup menu's font (ps3/host/menu_font.h): DejaVu Sans Bold (Bitstream Vera license,
# free to redistribute), ASCII 32..126, 8-bit coverage per pixel.
#   python3 tools/menu-font/make_font.py /usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf ps3/host/menu_font.h
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, out = sys.argv[1], sys.argv[2]
size = 40
font = ImageFont.truetype(ttf, size)
ascent, descent = font.getmetrics()
height = ascent + descent
glyphs = []
for c in range(32, 127):
    ch = chr(c)
    adv = int(round(font.getlength(ch)))
    w = max(adv, 1)
    img = Image.new("L", (w + 4, height), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    bbox = img.getbbox()
    if bbox is None:
        glyphs.append((adv, 0, 0, b""))
        continue
    x0, x1 = bbox[0], bbox[2]
    crop = img.crop((x0, 0, x1, height))
    glyphs.append((adv, x0, x1 - x0, crop.tobytes()))
with open(out, "w") as f:
    f.write("// Generated by tools/menu-font/make_font.py: DejaVu Sans Bold %dpx (Bitstream Vera license), ASCII 32..126.\n" % size)
    f.write("#pragma once\n#include <cstdint>\n\nnamespace menu_font {\n")
    f.write("constexpr int kHeight = %d, kAscent = %d;\n" % (height, ascent))
    f.write("struct Glyph { int16_t advance, x, w; uint32_t offset; };\n")
    data = bytearray()
    f.write("constexpr Glyph kGlyphs[95] = {\n")
    for adv, x0, w, px in glyphs:
        f.write("    {%d, %d, %d, %d},\n" % (adv, x0, w, len(data)))
        data += px
    f.write("};\n")
    f.write("constexpr uint8_t kPixels[%d] = {\n" % max(len(data), 1))
    for i in range(0, len(data), 32):
        f.write("    " + ",".join(str(b) for b in data[i:i + 32]) + ",\n")
    f.write("};\n}  // namespace menu_font\n")
print(len(data), "bytes", height, "px")
