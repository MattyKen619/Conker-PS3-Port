// Unhandled C++ exceptions end up here: log what they were.
static void on_terminate() {
    const char* what = "unknown exception";
    std::string text;
    if (auto e = std::current_exception()) {
        try { std::rethrow_exception(e); }
        catch (const std::exception& ex) { text = ex.what(); what = text.c_str(); }
        catch (...) {}
    } else {
        what = "std::terminate called without an exception";
    }
    ps3_crash_begin();
    ps3_log("\n[ps3] FATAL: unhandled C++ exception: %s\n", what);
    std::abort();
}

